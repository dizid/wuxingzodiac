// Renders the small "WUXINGZODIAC.ME" mark that the element video background
// function overlays in the corner of every clip (the bundled ffmpeg has no text
// filter). Run once after changing the look:  node scripts/generate-video-watermark.mjs
// Output: src/lib/element-video/server/watermark-png.ts (the PNG as base64, so it is
// bundled into the function without included_files) + a .png copy to look at.

import sharp from 'sharp'
import { mkdirSync, writeFileSync } from 'node:fs'

const width = 300
const height = 44
const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="${width}" height="${height}">
  <defs>
    <filter id="s" x="-10%" y="-30%" width="120%" height="160%">
      <feDropShadow dx="0" dy="1" stdDeviation="2" flood-color="#000" flood-opacity="0.75"/>
    </filter>
  </defs>
  <text x="${width - 4}" y="30" text-anchor="end" filter="url(#s)"
        font-family="Inter, Helvetica, Arial, DejaVu Sans, sans-serif" font-size="20" font-weight="700"
        letter-spacing="3" fill="#ffffff" fill-opacity="0.85">WUXINGZODIAC.ME</text>
</svg>`

const png = await sharp(Buffer.from(svg)).png({ compressionLevel: 9 }).toBuffer()
mkdirSync('scripts/sample-videos', { recursive: true })
writeFileSync('scripts/sample-videos/watermark.png', png)
writeFileSync(
  'src/lib/element-video/server/watermark-png.ts',
  `// Generated by scripts/generate-video-watermark.mjs, do not edit.\n` +
    `// ${width}x${height} PNG, "WUXINGZODIAC.ME", overlaid bottom-right on every element video.\n` +
    `export const WATERMARK_PNG_BASE64 =\n  '${png.toString('base64')}'\n`,
)
console.log(`Wrote src/lib/element-video/server/watermark-png.ts (${png.length} bytes)`)
